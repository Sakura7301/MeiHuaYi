/** 起卦工具返回给模型的完整文本。 */
export function castToolText(chart, recordId, extra = '') {
  const lines = ['【排盘】', chart, ''];
  if (recordId) lines.push(`（已自动保存卦例草稿，record_id = ${recordId}）`, '');
  lines.push(CAST_PROTOCOL);
  if (extra) lines.push('', extra);
  return lines.join('\n');
}